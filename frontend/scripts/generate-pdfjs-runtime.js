/**
 * Generates src/generated/pdfjsRuntime.ts from assets/pdf/*.pdfjs.
 *
 * The pdf.js runtime is stored as escaped JS string literals so the PDF
 * viewer can inline it into the WebView HTML — fully offline, no CDN.
 *
 * Run: node scripts/generate-pdfjs-runtime.js
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "assets", "pdf");
const outDir = path.join(root, "src", "generated");
const outFile = path.join(outDir, "pdfjsRuntime.ts");

function escapeForTemplateLiteral(s) {
    // Escape backslashes, backticks and ${ so the code survives inside a
    // JS template literal verbatim.
    return s
        .replace(/\\/g, "\\\\")
        .replace(/`/g, "\\`")
        .replace(/\$\{/g, "\\${");
}

const main = fs.readFileSync(path.join(srcDir, "pdf.min.pdfjs"), "utf8");
const worker = fs.readFileSync(path.join(srcDir, "pdf.worker.min.pdfjs"), "utf8");

if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

const content = `// AUTO-GENERATED by scripts/generate-pdfjs-runtime.js — do not edit.
// Source: assets/pdf/pdf.min.pdfjs + pdf.worker.min.pdfjs (pdf.js 3.11.174).
// These strings are inlined into the PDF viewer WebView so it works offline.

export const PDFJS_RUNTIME = \`${escapeForTemplateLiteral(main)}\`;

export const PDFJS_WORKER = \`${escapeForTemplateLiteral(worker)}\`;
`;

fs.writeFileSync(outFile, content, "utf8");
console.log(`Wrote ${outFile} (${(content.length / 1024).toFixed(0)} KB)`);