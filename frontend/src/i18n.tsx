const dictionaries: Record<Lang, Dict> = { en, fr };

// ---------------------------------------------------------------------------
// Context
// ---------------------------------------------------------------------------

type LangCtx = {
    lang: Lang;
    setLang: (l: Lang) => void;
    /** Dictionary for the active language. */
    t: Dict;
};

const Ctx = createContext<LangCtx | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [lang, setLangState] = useState<Lang>("en");

    // Load the locally persisted choice once at startup.
    useEffect(() => {
        (async () => {
            const saved = await storage.getItem<Lang>(LANG_KEY, "en");
            setLangState(saved === "fr" ? "fr" : "en");
        })();
    }, []);

    const setLang = useCallback((l: Lang) => {
        setLangState(l);
        // Local-only persistence — never synced to the backend.
        void storage.setItem(LANG_KEY, l);
    }, []);

    const value = useMemo<LangCtx>(
        () => ({ lang, setLang, t: dictionaries[lang] }),
        [lang, setLang]
    );

    // createElement (not JSX) so auto-formatters can't mangle the provider.
    return React.createElement(Ctx.Provider, { value }, children);
}

/** Active language + dictionary. Re-renders the caller on language change. */
export function useLanguage(): LangCtx {
    const ctx = useContext(Ctx);
    if (!ctx) throw new Error("useLanguage must be used within a LanguageProvider");
    return ctx;
}